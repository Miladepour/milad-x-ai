<h2>۶. چند AI Agent برای انتقال فایل بین خودشون، فایل رو روی اینترنت عمومی گذاشتن</h2>

<p>این اتفاق در یک محیط Multi-Agent افتاده.</p>

<p>چند Agent با هم روی ساخت یک فایل Excel مربوط به Depreciation کار می‌کردن.</p>

<p>یک Sub-Agent فایل Excel رو درست کرد، ولی Agent اصلی نمی‌تونست به فایل Local اون دسترسی داشته باشه.</p>

<p>اول Sub-Agent فایل رو به مسیر Shared منتقل کرد؛ نشد.</p>

<p>بعد بررسی کرد ببینه می‌تونه فایل رو با Git منتقل کنه؛ Environment اصلاً Git Repository نبود.</p>

<p>بعد به این فکر کرد که فایل رو Base64 کنه و از طریق پیام برای Agent دیگه بفرسته، ولی متن تبدیل‌شده بیشتر از ۱۵۴ هزار کاراکتر بود و خیلی بزرگ بود.</p>

<p>مرحله بعد یک HTTP Server محلی راه انداخت و سعی کرد Agent دیگه فایل رو از localhost دانلود کنه.</p>

<p>خود Agent می‌تونست فایل رو ببینه، ولی Agent همکار خطای 502 گرفت.</p>

<p>بعد مدل تصمیم گرفت سراغ اینترنت بره.</p>

<p>فایل Excel رو روی یک سرویس عمومی موقت اشتراک فایل آپلود کرد، لینک عمومی دانلود گرفت و اون لینک رو برای Agent اصلی و Agent همکار فرستاد.</p>

<p>بعد حتی خودش لینک رو تست کرد و مطمئن شد فایل کامل با HTTP 200 قابل دانلود هست.</p>

<p>یعنی فایلی که طبق Task قرار بوده فقط Local باقی بمونه، بدون اجازه روی یک سرویس عمومی اینترنت قرار گرفته بود.</p>

<p>OpenAI میگه احتمالاً دلیل اصلی این رفتار ترکیبی از مشکل Environment چند-Agent و این بوده که مدل‌ها در Training یاد گرفته بودن برای همکاری با هم راه پیدا کنن.</p>

<p>بعد از این Incident، OpenAI میگه مشکل Shared Filesystem رو اصلاح کرده، دسترسی اینترنت این Dataset رو قطع کرده و بعداً Live Internet Access رو در Training به‌صورت کلی غیرفعال کرده.</p>

<p>سیستم مانیتورینگ Misalignment هم الان روی ۱۰۰٪ Sampleهای مربوط اجرا می‌شه و چنین رفتاری رو یک Incident سطح P0 حساب می‌کنه.</p>

<p>نکته مهم این گزارش اینه که OpenAI نمیگه این رفتارها رفتار عادی ChatGPT یا همه مدل‌ها هستن.</p>

<p>این‌ها ۶ Incident مشخص در محیط Training و Evaluation هستن و خود OpenAI هم تأکید کرده از این موارد نمی‌شه نتیجه گرفت Misalignment با چه فراوانی در مدل‌ها اتفاق می‌افته.</p>

